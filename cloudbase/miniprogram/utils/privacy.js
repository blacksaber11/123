function readConsent() {
  try {
    return wx.getStorageSync(CONSENT_KEY) || null
  } catch (err) {
    return null
  }
}

/** 登录成功时写入同意留痕：协议版本 + 同意时间 */
function writeConsent() {
  const record = { version: PRIVACY_VERSION, at: new Date().toISOString(), agree: true }
  try {
    wx.setStorageSync(CONSENT_KEY, record)
  } catch (err) {
    /* 本地写入失败不阻断登录 */
  }
  return record
}

